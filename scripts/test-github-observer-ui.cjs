const fs = require('node:fs'), path = require('node:path'), assert = require('node:assert/strict')
const root = path.resolve(__dirname, '../devpilot-web')
const { parse, compileScript } = require(require.resolve('@vue/compiler-sfc', { paths: [root] }))
const esbuild = require(require.resolve('esbuild', { paths: [root] }))
const { chromium } = require(process.env.DEVPILOT_PLAYWRIGHT_MODULE || '/Users/miaomeng/.cache/codex-runtimes/codex-primary-runtime/dependencies/node/node_modules/playwright')
;(async () => {
  const script = compileScript(parse(fs.readFileSync(path.join(root, 'src/components/GithubObserverSettings.vue'), 'utf8')).descriptor, { id:'observer-test', inlineTemplate:true }).content
  const bundle = await esbuild.build({ stdin:{ contents:script.replace('export default', 'const Component =') + `\nimport {createApp} from 'vue';createApp(Component,{applicationId:'1',repositoryProvider:'GITHUB'}).mount('#app')`, resolveDir:root, loader:'ts' }, bundle:true, write:false, format:'iife', plugins:[{name:'mocks',setup(build){
    build.onResolve({filter:/^@\//}, args=>({path:args.path,namespace:'mock'}))
    build.onLoad({filter:/.*/,namespace:'mock'},args=>({contents:args.path.includes('stores/auth')
      ? `export function useAuthStore(){return {user:{id:'1'},hasAnyRole:()=>true}}`
      : `const response=()=>({data:{data:window.saved}});export const apiClient={get:async()=>response(),put:async(url,body)=>{window.writes.push(body);window.saved={revision:'r1',state:'SAVED_UNVERIFIED',credentialConfigured:true,expiresAt:body.expiresAt};if(window.fail)throw Error('fixture');return response()},delete:async()=>{window.saved={revision:'r2',state:'DISABLED',credentialConfigured:false,expiresAt:null};return response()}}`}))
  }}]})
  const browser = await chromium.launch({headless:true})
  try {
    const page = await browser.newPage()
    await page.route('**/*', route=>route.fulfill({contentType:'text/html',body:'<div id="app"></div>'}))
    await page.goto('http://127.0.0.1:19997/')
    await page.evaluate(()=>{window.saved={revision:'initial',state:'DISABLED',credentialConfigured:false,expiresAt:null};window.writes=[]})
    await page.addScriptTag({content:bundle.outputFiles[0].text})
    await page.getByRole('button',{name:'自动核对设置 · GitHub observer'}).click()
    const save=page.getByRole('button',{name:'保存并开启核对'}), input=page.getByLabel('查询凭据 · 本仓库 Actions: read'), consent=page.getByRole('checkbox')
    await input.fill('fixture_observer_token')
    assert.equal(await save.isDisabled(),true)
    await consent.check();await save.click()
    await page.getByText('配置已保存。', {exact:false}).waitFor()
    assert.equal(await input.inputValue(),'');assert.equal(await consent.isChecked(),false)
    assert.equal(await page.evaluate(()=>window.writes[0].consent),true)
    assert.equal(await page.evaluate(()=>localStorage.length+sessionStorage.length),0)
    await page.getByRole('button',{name:'关闭并清除凭据'}).click()
    await page.getByText('已关闭自动核对并删除', {exact:false}).waitFor()
    await input.fill('fixture_observer_token');await consent.check()
    await page.evaluate(()=>{window.fail=true})
    await save.click();await page.getByRole('alert').waitFor()
    assert.equal(await save.isDisabled(),true)
    await page.getByRole('button',{name:'刷新配置'}).click()
    await page.getByText('已保存，凭据尚未验证 Saved',{exact:false}).waitFor()
    assert.equal(await page.evaluate(()=>window.writes.length),2)
    await page.evaluate(()=>{window.saved.nextCheckAt='2026-09-07T00:00:00Z'})
    await page.getByRole('button',{name:'刷新配置'}).click()
    await page.getByText('最早再次核对时间：2026-09-07T00:00:00Z',{exact:false}).waitFor()
    await page.getByText('不保证该时刻执行或授权有效',{exact:false}).waitFor()
    console.log('PASS: actual settings component requires consent, clears credentials, disables, and reads back uncertain writes without resubmission; no external HTTP')
  } finally {await browser.close()}
})().catch(error=>{console.error(error);process.exitCode=1})
