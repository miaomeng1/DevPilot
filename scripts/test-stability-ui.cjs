// Only against the isolated OnboardingUiSmokeApplication, never a real integrated instance.
const { chromium } = require(process.env.PLAYWRIGHT_MODULE || 'playwright')
const assert = require('node:assert/strict')
const { randomBytes, createHmac } = require('node:crypto')
const { mkdtempSync } = require('node:fs')
const { tmpdir } = require('node:os')
const { join } = require('node:path')

async function main() {
  const ui = 'http://127.0.0.1:19091'
  const api = 'http://127.0.0.1:19090'
  assert.equal((await (await fetch(api + '/api/auth/setup/status')).json()).data.setupRequired, true,
    'Requires a fresh isolated fixture; refusing to reuse an initialized instance')
  const output = mkdtempSync(join(tmpdir(), 'devpilot-stability-ui-'))
  const browser = await chromium.launch({ headless: true })
  try {
    const context = await browser.newContext({ viewport: { width: 1440, height: 1000 } })
    const creationKeys = []
    const renewalKeys = []
    const renewalTokens = []
    const droppedNames = new Set()
    let authorization = ''
    const approvalRequests = [], approvalResults = []
    // Keep all API calls in the test backend. Abort any external request.
    await context.route('**/*', async route => {
      const url = new URL(route.request().url())
      if (url.origin !== ui) return route.abort()
      if (url.pathname.startsWith('/api/')) {
        authorization = route.request().headers().authorization || authorization
        const response = await route.fetch({ url: api + url.pathname + url.search })
        if (/\/builds\/\d+\/approval$/.test(url.pathname) && route.request().method() === 'POST') {
          approvalRequests.push(route.request().postDataJSON())
          assert.equal(response.status(), approvalRequests.length === 3 ? 409 : 200)
          if (response.status() === 200) approvalResults.push((await response.json()).data)
          if (approvalRequests.length === 1) return route.abort('failed')
        }
        if (/^\/api\/servers\/\d+\/registration$/.test(url.pathname) && route.request().method() === 'POST') {
          const body = route.request().postDataJSON()
          renewalKeys.push(body.requestId)
          assert.equal(response.status(), 200)
          renewalTokens.push((await response.json()).data.agentToken)
          if (renewalKeys.length === 1) return route.abort('failed')
        }
        if (url.pathname === '/api/servers' && route.request().method() === 'POST') {
          const body = route.request().postDataJSON()
          creationKeys.push(body.requestId)
          if (!droppedNames.has(body.name)) { droppedNames.add(body.name); return route.abort('failed') }
        }
        return route.fulfill({ response })
      }
      return route.continue()
    })
    const page = await context.newPage()
    const errors = []
    page.on('pageerror', error => errors.push(error.message))
    await page.goto(ui + '/login')
    await page.getByRole('button', { name: 'Create administrator' }).waitFor()
    await page.locator('input[autocomplete="username"]').fill('ui-stability-admin')
    const password = 'Dp9!' + randomBytes(18).toString('hex')
    await page.locator('input[autocomplete="new-password"]').nth(0).fill(password)
    await page.locator('input[autocomplete="new-password"]').nth(1).fill(password)
    await page.getByRole('button', { name: 'Create administrator' }).click()
    await page.waitForURL('**/setup')
    await page.getByLabel('Public URL').fill(api)
    await page.getByLabel('平台地址', { exact: true }).fill('https://synthetic.invalid')
    await page.getByLabel('API Key', { exact: true }).fill('fixture-' + randomBytes(18).toString('hex'))
    await page.getByRole('button', { name: '保存初始化配置' }).click()
    await page.getByText('已保存 · 尚未验证', { exact: true }).waitFor()
    assert.equal(await page.getByLabel('API Key', { exact: true }).inputValue(), '')
    await page.getByRole('button', { name: '验证已保存的连接' }).click()
    await page.locator('section').filter({ has: page.getByRole('heading', { name: /03 · Dokploy/ }) })
      .getByText('验证通过', { exact: true }).waitFor()
    await page.getByPlaceholder('personal-server').fill('ui-fixture-server')
    await page.getByRole('button', { name: '添加并保存服务器选择' }).click()
    await page.getByRole('alert').waitFor()
    await page.reload()
    await page.getByPlaceholder('personal-server').waitFor()
    assert.equal(await page.getByPlaceholder('personal-server').inputValue(), 'ui-fixture-server')
    await page.getByRole('button', { name: '添加并保存服务器选择' }).click()
    await page.getByRole('button', { name: '隐藏安装命令' }).waitFor()
    assert.equal(creationKeys.length, 2)
    assert.ok(creationKeys[0] && creationKeys[0] === creationKeys[1], 'Reload must reuse the same creation request')
    const command = await page.locator('textarea[readonly]').inputValue()
    assert.ok(command.includes(api), 'Agent command must use saved public URL')
    await page.getByRole('button', { name: '隐藏安装命令' }).click()
    await page.reload()
    await page.getByRole('option', { name: 'ui-fixture-server' }).waitFor({ state: 'attached' })
    assert.equal(await page.getByRole('option', { name: 'ui-fixture-server' }).count(), 1)
    assert.notEqual(await page.getByLabel('选择服务器').inputValue(), '')
    assert.equal(await page.locator('textarea[readonly]').count(), 0)
    assert.equal(await page.getByLabel('API Key', { exact: true }).inputValue(), '')
    await page.screenshot({ path: join(output, 'setup-desktop.png'), fullPage: true })
    await page.setViewportSize({ width: 390, height: 844 })
    assert.ok(await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth), 'Mobile setup must not overflow horizontally')
    await page.screenshot({ path: join(output, 'setup-mobile.png'), fullPage: true })
    await page.setViewportSize({ width: 1440, height: 1000 })
    await page.goto(ui + '/cicd/onboarding')
    await page.getByLabel('复用初始化中的 Dokploy 授权', { exact: false }).check()
    assert.equal(await page.getByLabel('部署平台 API Key', { exact: false }).count(), 0)
    await page.getByPlaceholder('https://github.com/you/blog').fill('https://github.com/example/smoke')
    await page.getByLabel('仓库 Token', { exact: false }).fill('fixture-repository-token')
    await page.getByRole('button', { name: '检查授权与识别项目' }).click()
    await page.getByRole('heading', { name: '2 · 确认运行参数' }).waitFor()
    assert.equal(await page.getByLabel('容器内部端口 Internal').inputValue(), '8080')
    assert.equal(await page.getByRole('button', { name: '自动完成接入配置 →' }).isDisabled(), true)
    await page.screenshot({ path: join(output, 'onboarding-inspected.png'), fullPage: true })
    await page.goto(ui + '/servers')
    await page.getByRole('button', { name: 'Add server' }).click()
    await page.getByPlaceholder('prod-server-01').fill('ui-standalone-server')
    await page.getByRole('button', { name: 'Generate Agent token' }).click()
    await page.locator('.server-dialog .form-error').waitFor()
    await page.reload()
    await page.getByRole('button', { name: 'Add server' }).click()
    assert.equal(await page.getByPlaceholder('prod-server-01').inputValue(), 'ui-standalone-server')
    await page.getByRole('button', { name: 'Generate Agent token' }).click()
    await page.getByRole('heading', { name: 'Install DevPilot Agent' }).waitFor()
    assert.equal(creationKeys.length, 4)
    assert.equal(creationKeys[2], creationKeys[3])
    await page.getByRole('button', { name: 'Close', exact: true }).click()
    await page.reload()
    await page.getByText('ui-standalone-server', { exact: true }).waitFor()
    assert.equal(await page.getByText('ui-standalone-server', { exact: true }).count(), 1)
    const renewalButton = () => page.getByRole('row').filter({ hasText: 'ui-standalone-server' }).getByRole('button', { name: '重新签发 Token' })
    await renewalButton().click()
    assert.equal(await page.getByRole('button', { name: '确认撤销并签发' }).isDisabled(), true)
    await page.getByLabel('我确认目标服务器', { exact: false }).check()
    await page.getByRole('button', { name: '确认撤销并签发' }).click()
    await page.getByRole('alert').waitFor()
    await page.reload()
    await renewalButton().click()
    await page.getByText('发现未完成的签发请求', { exact: false }).waitFor()
    await page.getByLabel('我确认目标服务器', { exact: false }).check()
    await page.getByRole('button', { name: '恢复同一次签发' }).click()
    await page.getByRole('button', { name: '已保存，关闭' }).waitFor()
    assert.equal(renewalKeys.length, 2)
    assert.equal(renewalKeys[0], renewalKeys[1])
    assert.ok(renewalTokens[0] === renewalTokens[1], 'Renewal replay must return the same credential')
    assert.equal(await page.getByText(renewalTokens[1], { exact: true }).isVisible(), false)
    assert.ok(!(await page.evaluate(() => JSON.stringify(localStorage))).includes(renewalTokens[1]), 'Browser storage must not contain Agent credentials')
    await page.setViewportSize({ width: 390, height: 844 })
    assert.ok(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth), 'Renewal must fit mobile width')
    await page.screenshot({ path: join(output, 'renewal-masked-mobile.png'), fullPage: true })
    await page.getByRole('button', { name: '已保存，关闭' }).click()
    assert.equal(await page.evaluate(() => Object.keys(localStorage).filter(key => key.startsWith('devpilot.agent-renewal.')).length), 0)
    await page.setViewportSize({ width: 1440, height: 1000 })
    await page.getByRole('button', { name: 'Add server' }).click()
    await page.getByPlaceholder('prod-server-01').fill('ui-resolved-creation')
    await page.getByRole('button', { name: 'Generate Agent token' }).click()
    await page.locator('.server-dialog .form-error').waitFor()
    assert.equal(creationKeys.length, 5)
    await page.getByRole('button', { name: '核对原服务器（只读）' }).click()
    await page.getByText('创建结果仍可恢复', { exact: false }).waitFor()
    assert.equal(await page.getByRole('button', { name: '结束旧创建请求', exact: true }).isDisabled(), true)
    await page.getByLabel('我已核对上述记录', { exact: false }).check()
    await page.getByRole('button', { name: '结束旧创建请求', exact: true }).click()
    assert.equal(await page.getByPlaceholder('prod-server-01').inputValue(), '')
    assert.equal(creationKeys.length, 5, 'Read-only inspection and finishing must not create another server')
    await page.getByRole('button', { name: 'Close', exact: true }).click()
    await page.reload()
    await page.getByText('ui-resolved-creation', { exact: true }).waitFor()
    assert.equal(await page.getByText('ui-resolved-creation', { exact: true }).count(), 1)
    // Seed only the isolated backend via real authenticated APIs and a signed build callback.
    async function fixture(path, method = 'GET', body, headers = {}) {
      const response = await fetch(api + '/api' + path, { method,
        headers: { authorization, 'Content-Type': 'application/json', ...headers },
        body: body === undefined ? undefined : JSON.stringify(body) })
      assert.equal(response.status, 200, `Fixture API failed: ${method} ${path}`)
      return (await response.json()).data
    }
    assert.ok(authorization, 'Expected authenticated browser session')
    const servers = await fixture('/servers')
    const target = servers.find(server => server.name === 'ui-fixture-server')
    assert.ok(target)
    const app = await fixture('/applications', 'POST', { name: 'UI release fixture', code: 'ui-release',
      environment: 'PRODUCTION', serverId: target.id })
    const config = await fixture(`/cicd/configurations/${app.id}`, 'PUT', {
      repositoryProvider: 'GITHUB', repositoryUrl: 'https://github.com/example/smoke', branchName: 'main',
      deploymentProvider: 'COOLIFY', deploymentWebhookUrl: 'http://127.0.0.1:9/deploy',
      autoDeploy: false, productionApproval: true, rotateCallbackSecret: false,
    })
    const buildKey = createHmac('sha256', config.oneTimeCallbackSecret).update('devpilot-build-status-v1').digest('hex')
    const buildBody = { externalRunId: 'build:ui-77-1', commitSha: 'a'.repeat(40), branchName: 'main',
      status: 'SUCCEEDED', testStatus: 'PASSED', securityStatus: 'PASSED',
      imageUri: 'ghcr.io/example/smoke@sha256:' + 'b'.repeat(64) }
    const build = await fixture('/cicd/webhooks/ui-release/builds', 'POST', buildBody, {
      'X-DevPilot-Signature': 'sha256=' + createHmac('sha256', buildKey).update(JSON.stringify(buildBody)).digest('hex'),
    })
    await page.goto(ui + `/cicd?application=${app.id}`)
    const panel = page.locator('.manual-approvals')
    await panel.getByLabel('选择成功构建').selectOption(build.id)
    await panel.getByRole('button', { name: '核对发布目标' }).click()
    await panel.locator('.approval-context').waitFor()
    assert.equal(await panel.getByRole('button', { name: '确认此版本', exact: true }).isDisabled(), true)
    await panel.getByLabel('我已核对目标', { exact: false }).check()
    await panel.getByRole('button', { name: '确认此版本', exact: true }).click()
    await panel.getByRole('alert').waitFor()
    await page.reload()
    await panel.getByLabel('选择成功构建').selectOption(build.id)
    await panel.getByRole('button', { name: '核对发布目标' }).click()
    await panel.getByText('发现未完成的确认请求', { exact: false }).waitFor()
    assert.equal(await panel.getByRole('button', { name: '恢复同一次确认' }).isDisabled(), true)
    await panel.getByLabel('我已核对目标', { exact: false }).check()
    await panel.getByRole('button', { name: '恢复同一次确认' }).click()
    await panel.getByRole('status').waitFor()
    assert.equal(approvalRequests.length, 2)
    assert.deepEqual(approvalRequests[0], approvalRequests[1], 'Reload must replay the exact approval snapshot')
    assert.deepEqual(approvalResults[0], approvalResults[1], 'Replay must preserve identity and confirmation time')
    assert.equal(approvalResults[1].approvedUsername, 'ui-stability-admin')
    assert.equal((await fixture(`/cicd/applications/${app.id}/release-approvals`)).length, 1)
    assert.equal((await fixture(`/cicd/applications/${app.id}/deployments`)).length, 0)
    assert.equal(await page.evaluate(() => Object.keys(localStorage).filter(key => key.startsWith('devpilot.release-approval.')).length), 0)
    page.once('dialog', dialog => dialog.accept())
    await panel.getByRole('button', { name: '撤销确认', exact: true }).click()
    await panel.getByText('已撤销', { exact: true }).waitFor()
    assert.ok((await fixture(`/cicd/applications/${app.id}/release-approvals`))[0].revokedAt)
    await page.setViewportSize({ width: 390, height: 844 })
    await panel.scrollIntoViewIfNeeded()
    await panel.screenshot({ path: join(output, 'approval-revoked-mobile.png') })
    assert.equal(await panel.getByText('GitHub Run workflow', { exact: false }).count(), 0)
    await page.setViewportSize({ width: 1440, height: 1000 })
    await panel.getByRole('button', { name: '核对发布目标' }).click()
    await panel.locator('.approval-context').waitFor()
    await fixture(`/cicd/configurations/${app.id}`, 'PUT', {
      repositoryProvider: 'GITHUB', repositoryUrl: 'https://github.com/example/smoke', branchName: 'main',
      deploymentProvider: 'COOLIFY', deploymentWebhookUrl: 'http://127.0.0.1:9/deploy',
      autoDeploy: false, productionApproval: true, rotateCallbackSecret: false, healthTimeoutSeconds: 180,
    })
    await panel.getByLabel('我已核对目标', { exact: false }).check()
    await panel.getByRole('button', { name: '确认此版本', exact: true }).click()
    await panel.getByRole('alert').waitFor()
    assert.equal(await panel.getByRole('button', { name: '重新读取目标', exact: true }).isDisabled(), true)
    assert.equal((await fixture(`/cicd/applications/${app.id}/release-approvals`)).length, 1)
    await panel.getByLabel('我已核对记录，结束旧请求', { exact: false }).check()
    await panel.getByRole('button', { name: '重新读取目标', exact: true }).click()
    await panel.getByRole('button', { name: '确认此版本', exact: true }).waitFor()
    assert.equal(await panel.getByLabel('我已核对目标', { exact: false }).isChecked(), false)
    assert.equal(await panel.getByRole('button', { name: '确认此版本', exact: true }).isDisabled(), true)
    await panel.getByLabel('我已核对目标', { exact: false }).check()
    await panel.getByRole('button', { name: '确认此版本', exact: true }).click()
    await panel.locator('article').filter({ hasText: '待使用' }).waitFor()
    assert.equal(approvalRequests.length, 4)
    assert.notEqual(approvalRequests[2].expectedFingerprint, approvalRequests[3].expectedFingerprint)
    assert.notEqual(approvalRequests[2].requestId, approvalRequests[3].requestId)
    assert.equal((await fixture(`/cicd/applications/${app.id}/release-approvals`)).length, 2)
    assert.equal((await fixture(`/cicd/applications/${app.id}/deployments`)).length, 0)
    assert.deepEqual(errors, [])
    console.log('Passed: setup, server recovery, credential renewal, approval lost-response/reload replay, revocation, stale-target rejection and explicit reconfirmation without deployment.')
    console.log('Screenshots: ' + output)
  } finally { await browser.close() }
}
main().catch(error => { console.error(error.message); process.exitCode = 1 })
